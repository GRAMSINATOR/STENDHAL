"""EXP-019 scorer. Standard library only.

The decision rules live here, written before any output exists. They must not be
edited after the first judgment is committed; see README "Pre-registered analysis".

    python3 score.py            # prints the results report as Markdown
    python3 score.py --selftest
"""
from __future__ import annotations
import argparse
import itertools
import json
import re
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_FAMILIES = ("gpt", "claude")
N_SUPPORT = 4  # briefs (of 6) where the arm must beat A, in both model families
MAX_HARM = 1   # briefs where A may beat the arm, in either family, for SUPPORTED
N_REJECT = 4   # briefs where the arm fails to beat A, in both families, for REJECTED


def family(judge: str) -> str:
    return re.match(r"[a-z]+", judge).group(0)


def load(root: Path):
    keys = {p.stem: json.loads(p.read_text()) for p in sorted((root / "key").glob("*.json"))}
    judgments = defaultdict(dict)  # brief -> judge -> judgment
    for p in sorted((root / "judgments").glob("*/*.json")):
        judgments[p.stem][p.parent.name] = json.loads(p.read_text())
    predictions = defaultdict(dict)  # predictor -> brief -> prediction
    for p in sorted((root / "predictions").glob("*/*.json")):
        predictions[p.parent.name][p.stem] = json.loads(p.read_text())
    return keys, judgments, predictions


def condition_tiers(key: dict, judge: str, judgment: dict) -> dict[str, int]:
    mapping = key["judges"][judge]
    tiers = {}
    for i, tier in enumerate(judgment["ranking"]):
        for label in tier:
            for cond in key["passages"][mapping[label]]:
                tiers[cond] = i
    missing = {c for conds in key["passages"].values() for c in conds} - tiers.keys()
    if missing:
        raise SystemExit(f"{key['brief']}/{judge}: ranking omits conditions {sorted(missing)}")
    return tiers


def identical(key: dict, x: str, y: str) -> bool:
    return any(x in conds and y in conds for conds in key["passages"].values())


def majority(key, judges: dict, x: str, y: str) -> str:
    """Return x, y, 'tie' or 'identical' for one brief and one group of judges."""
    if identical(key, x, y):
        return "identical"
    xs = ys = 0
    for judge, judgment in judges.items():
        t = condition_tiers(key, judge, judgment)
        xs += t[x] < t[y]
        ys += t[y] < t[x]
    return x if xs > ys else y if ys > xs else "tie"


def verdict(results: dict[str, dict[str, str]], arm: str) -> str:
    """results: family -> brief -> majority outcome of (A, arm)."""
    wins = {f: sum(r == arm for r in results[f].values()) for f in MODEL_FAMILIES}
    harms = {f: sum(r == "A" for r in results[f].values()) for f in MODEL_FAMILIES}
    fails = {f: sum(r != arm for r in results[f].values()) for f in MODEL_FAMILIES}
    if all(wins[f] >= N_SUPPORT and harms[f] <= MAX_HARM for f in MODEL_FAMILIES):
        return "SUPPORTED"
    if all(fails[f] >= N_REJECT for f in MODEL_FAMILIES):
        return "REJECTED"
    return "INCONCLUSIVE"


def report(root: Path) -> str:
    keys, judgments, predictions = load(root)
    briefs = sorted(keys)
    groups = defaultdict(lambda: defaultdict(dict))  # family -> brief -> judge -> judgment
    for b in briefs:
        for judge, j in judgments[b].items():
            groups[family(judge)][b][judge] = j
    conds = sorted({c for k in keys.values() for cs in k["passages"].values() for c in cs})
    pairs = list(itertools.combinations(conds, 2))
    out = ["# EXP-019 results (generated by score.py)", ""]

    # Pairwise majorities, every group reported separately, never pooled.
    maj = defaultdict(dict)  # (family, pair) -> brief -> outcome
    for fam in sorted(groups):
        out += [f"## Pairwise majorities: {fam} judges", "",
                "| Brief | " + " | ".join(f"{x} vs {y}" for x, y in pairs) + " |",
                "|---|" + "---|" * len(pairs)]
        for b in briefs:
            row = []
            for x, y in pairs:
                r = majority(keys[b], groups[fam][b], x, y) if groups[fam][b] else "n/a"
                maj[(fam, (x, y))][b] = r
                row.append(r)
            out.append(f"| {b} | " + " | ".join(row) + " |")
        out.append("")

    # H1, by the pre-registered rule; humans are reported but do not decide it.
    out += ["## H1: does STENDHAL beat the untreated baseline?", ""]
    for arm, role in (("C", "primary"), ("D", "secondary")):
        if arm not in conds:
            continue
        res = {f: maj[(f, ("A", arm))] for f in MODEL_FAMILIES}
        if not all(len(res[f]) == len(briefs) and "n/a" not in res[f].values() for f in MODEL_FAMILIES):
            out += [f"- {arm} ({role}): incomplete, since both model families must judge every brief", ""]
            continue
        harm = [f"{b} ({f})" for f in MODEL_FAMILIES for b, r in res[f].items() if r == "A"]
        out += [f"- **{arm} vs A ({role}): {verdict(res, arm)}**",
                f"  - A beat {arm} (intervention made it worse): {', '.join(harm) or 'none'}"]
    out.append("")

    # NO_EDIT: an abstention is judged by whether the available ordinary edit helped.
    abst = [b for b in briefs if identical(keys[b], "A", "C")]
    if abst:
        out += ["## NO_EDIT decisions (proxy: did the ordinary revision B beat A?)", ""]
        for b in abst:
            cells = ", ".join(f"{f}: {maj[(f, ('A', 'B'))].get(b, 'n/a')}" for f in sorted(groups))
            out.append(f"- {b}: A vs B majority: {cells}. A or a tie means the abstention avoided a harmful edit; B means it missed an improvement.")
        out.append("")

    # Disagreement between model families is reported, not averaged.
    out += ["## Model-family disagreements", ""]
    dis = [f"- {b} {x} vs {y}: gpt={maj[('gpt', (x, y))].get(b)}, claude={maj[('claude', (x, y))].get(b)}"
           for b in briefs for x, y in pairs
           if maj[("gpt", (x, y))].get(b) != maj[("claude", (x, y))].get(b)]
    out += (dis or ["- none"]) + [""]

    # Fidelity problems flagged by judges, per condition.
    out += ["## Fidelity problems flagged (count of judge mentions)", ""]
    for fam in sorted(groups):
        counts = defaultdict(int)
        for b in briefs:
            for judge, j in groups[fam][b].items():
                for label, p in j["passages"].items():
                    n = len([x for x in p.get("fidelity_problems", []) if x.strip().lower() != "none"])
                    for c in keys[b]["passages"][keys[b]["judges"][judge][label]]:
                        counts[c] += n
        out.append(f"- {fam}: " + ", ".join(f"{c}={counts[c]}" for c in conds))
    out.append("")

    # H2: prediction accuracy against each model family's majority.
    out += ["## H2: prediction accuracy", "",
            "| Predictor | Judges | Pairs scored | Accuracy | Mean confidence | Foresaw harm (A beat C) |",
            "|---|---|---|---|---|---|"]
    for pred in sorted(predictions):
        for fam in MODEL_FAMILIES:
            score, conf, harm_hit, harm_n = [], [], 0, 0
            for b, p in predictions[pred].items():
                for entry in p["pairwise"]:
                    x, y = entry["pair"]
                    actual = maj[(fam, tuple(sorted((x, y))))].get(b)
                    if actual in (None, "identical", "n/a"):
                        continue
                    guess = entry["predicted_winner"]
                    score.append(1.0 if guess == actual else 0.5 if actual == "tie" else 0.0)
                    conf.append(entry["confidence"])
                    if sorted((x, y)) == ["A", "C"] and actual == "A":
                        harm_n += 1
                        harm_hit += guess == "A"
            if score:
                out.append(f"| {pred} | {fam} | {len(score)} | {sum(score) / len(score):.2f} | "
                           f"{sum(conf) / len(conf):.2f} | {harm_hit}/{harm_n} |")
    out += ["", "STENDHAL's perception adds something only if `stendhal` beats `control` "
            "with both model families. With this few pairs, treat any gap as an indication, not a finding.", ""]
    return "\n".join(out)


def selftest() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        judges = ["gpt1", "gpt2", "claude1", "claude2"]
        for i in range(6):
            b = f"X{i}"
            no_edit = i == 5
            passages = {"p1": ["A", "C"], "p2": ["B"]} if no_edit else {"p1": ["A"], "p2": ["B"], "p3": ["C"]}
            mapping = {j: {lab: pid for lab, pid in zip("KMT", passages)} for j in judges}
            (root / "key").mkdir(exist_ok=True)
            (root / "key" / f"{b}.json").write_text(json.dumps({"brief": b, "passages": passages, "judges": mapping}))
            for j in judges:
                inv = {pid: lab for lab, pid in mapping[j].items()}
                # C beats A in briefs 0-3; A beats C in brief 4; brief 5 is NO_EDIT.
                order = ["p3", "p1", "p2"] if i < 4 else ["p1", "p2", "p3"]
                order = [p for p in order if p in passages]
                d = root / "judgments" / j
                d.mkdir(parents=True, exist_ok=True)
                (d / f"{b}.json").write_text(json.dumps({
                    "ranking": [[inv[p]] for p in order],
                    "passages": {inv[p]: {"fidelity_problems": ["none"]} for p in passages}}))
            for pred, guess in (("stendhal", "C"), ("control", "A")):
                d = root / "predictions" / pred
                d.mkdir(parents=True, exist_ok=True)
                pw = [] if no_edit else [{"pair": ["A", "C"], "predicted_winner": guess, "confidence": 0.7}]
                (d / f"{b}.json").write_text(json.dumps({"pairwise": pw}))
        text = report(root)
        assert "**C vs A (primary): SUPPORTED**" in text, text
        assert "X4 (gpt)" in text and "X4 (claude)" in text
        assert "- X5: A vs B majority" in text
        assert "| stendhal | gpt | 5 | 0.80 |" in text, text
        assert "| control | claude | 5 | 0.20 | 0.70 | 1/1 |" in text, text
        res = {f: {f"X{i}": ("A" if i < 4 else "C") for i in range(6)} for f in MODEL_FAMILIES}
        assert verdict(res, "C") == "REJECTED"
        res["gpt"] = {f"X{i}": "C" for i in range(6)}
        assert verdict(res, "C") == "INCONCLUSIVE"
    print("score selftest: ok")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    if ap.parse_args().selftest:
        selftest()
    else:
        print(report(HERE))


if __name__ == "__main__":
    sys.exit(main())
